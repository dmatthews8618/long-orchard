#!/usr/bin/env node
// Combines recruitment runs (tools/recruitment.mjs --json) into a Markdown report.
//   node tools/recruitment-report.mjs out.md run1.json run2.json ...
import fs from 'node:fs';

const [outFile, ...files] = process.argv.slice(2);
const runs = files.map((f) => JSON.parse(fs.readFileSync(f, 'utf8')));
const L = [];
const pct = (a, b) => (b > 0 ? `${((100 * a) / b).toFixed(a / b < 0.01 ? 2 : 1)}%` : '–');
const SITES = ['under Bellfruit', 'under Lantern Pear', 'gap or deadwood', 'open'];
const SP = { bellfruit: 'Bellfruit', lantern: 'Lantern Pear' };

L.push('# Recruitment: from seed to flowering tree');
L.push('');
L.push(`Development worlds only (seeds ${runs.map((r) => r.seed).join(', ')}), ${runs[0].years} orchard years each: about one Bellfruit lifetime. Engine 0.1.1. Generated by \`tools/recruitment.mjs\` and \`tools/recruitment-report.mjs\`; the tracer only listens to the engine and does not change the worlds.`);
L.push('');
L.push('Sites are judged on the day a seed germinates: under the crown of a living Bellfruit or Lantern Pear, in a gap (ground once under a crown that has since died, or on more than 5 kg of deadwood), or open ground elsewhere.');
L.push('');

for (const sp of ['bellfruit', 'lantern']) {
  L.push(`## ${SP[sp]}`);
  L.push('');
  L.push('### Seeds');
  L.push('');
  L.push('| World | Source | Seeds made | Eaten by mice | Rotted | Germinated | Crowded out at once |');
  L.push('|---|---|---|---|---|---|---|');
  for (const r of runs) {
    for (const origin of ['founding stock', 'orchard-born']) {
      const f = r.seedFunnel[`${sp}|${origin}`];
      if (!f) continue;
      L.push(`| ${r.seed} | ${origin} | ${f.made} | ${f.eaten} (${pct(f.eaten, f.made)}) | ${f.rotted} (${pct(f.rotted, f.made)}) | ${f.germinated} (${pct(f.germinated, f.made)}) | ${f.crowded} |`);
    }
  }
  L.push('');
  L.push('### Seedlings, by where they germinated (all worlds together)');
  L.push('');
  L.push('| Site | Source | Germinated | Established | Reached flowering | Still alive at end | Main causes of seedling death |');
  L.push('|---|---|---|---|---|---|---|');
  for (const site of SITES) {
    for (const origin of ['founding stock', 'orchard-born']) {
      const agg = { germinated: 0, established: 0, flowered: 0, aliveNow: 0, causes: {} };
      for (const r of runs) {
        const f = r.funnel[`${sp}|${site}|${origin}`];
        if (!f) continue;
        agg.germinated += f.germinated; agg.established += f.established; agg.flowered += f.flowered; agg.aliveNow += f.aliveNow;
        for (const [k, v] of Object.entries(f.causes)) agg.causes[k] = (agg.causes[k] || 0) + v;
      }
      if (!agg.germinated) continue;
      const tot = Object.values(agg.causes).reduce((a, b) => a + b, 0);
      const causes = Object.entries(agg.causes).sort((a, b) => b[1] - a[1]).slice(0, 3).map(([k, v]) => `${k} ${pct(v, tot)}`).join(', ');
      L.push(`| ${site} | ${origin} | ${agg.germinated} | ${agg.established} (${pct(agg.established, agg.germinated)}) | ${agg.flowered} | ${agg.aliveNow} | ${causes} |`);
    }
  }
  L.push('');
}

L.push('## Over a lifetime');
L.push('');
L.push('Flowering trees by decade: founding trees still standing, and trees born in the orchard.');
L.push('');
for (const r of runs) {
  L.push(`### World ${r.seed}`);
  L.push('');
  L.push('| Year | Bellfruit flowering (founding / born here) | Bellfruit young | Lantern Pear flowering (founding / born here) | Lantern Pear young | Deepest generation | Seeds waiting (Bellfruit / Lantern) |');
  L.push('|---|---|---|---|---|---|---|');
  for (const d of r.byDecade) {
    L.push(`| ${d.year} | ${d.bellAdultsFounding} / ${d.bellAdultsBorn} | ${d.bellJuveniles} | ${d.lanternAdultsFounding} / ${d.lanternAdultsBorn} | ${d.lanternJuveniles} | ${d.maxGen} | ${d.seedsBell} / ${d.seedsLantern} |`);
  }
  L.push('');
}
fs.writeFileSync(outFile, `${L.join('\n')}\n`);
console.log(`wrote ${outFile}`);
